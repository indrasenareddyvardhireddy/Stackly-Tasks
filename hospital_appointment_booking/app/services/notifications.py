
import logging
import smtplib
from email.message import EmailMessage
from typing import Optional

from app.config import settings

logger = logging.getLogger(__name__)


def send_email(to_email: str, subject: str, body: str) -> bool:
    """Send an email through SMTP."""
    if not all([
        settings.SMTP_HOST,
        settings.SMTP_USERNAME,
        settings.SMTP_PASSWORD,
    ]):
        logger.error("SMTP is not configured.")
        return False

    try:
        msg = EmailMessage()
        msg["Subject"] = subject
        msg["From"] = settings.SMTP_FROM or settings.SMTP_USERNAME
        msg["To"] = to_email
        msg.set_content(body)

        with smtplib.SMTP(
            settings.SMTP_HOST,
            settings.SMTP_PORT,
            timeout=20,
        ) as server:
            server.ehlo()
            server.starttls()
            server.ehlo()
            server.login(
                settings.SMTP_USERNAME,
                settings.SMTP_PASSWORD,
            )
            server.send_message(msg)

        logger.info("Email sent successfully to %s", to_email)
        return True

    except Exception:
        logger.exception("Email delivery failed to %s", to_email)
        return False


def send_registration_email(
    patient_name: str,
    patient_email: str,
) -> bool:
    """Send patient registration confirmation."""
    subject = "Welcome to Hospital Appointment Booking"
    body = (
        f"Hello {patient_name},\n\n"
        "Your registration was successful.\n\n"
        "You can now log in and book appointments with our doctors.\n\n"
        "Regards,\nHospital Appointment Booking Team"
    )
    return send_email(patient_email, subject, body)


def send_doctor_account_email(
    doctor_name: str,
    doctor_email: str,
    login_url: Optional[str] = None,
) -> bool:
    """Notify a doctor that an account has been created."""
    subject = "Your Doctor Account Has Been Created"
    body = (
        f"Hello Dr. {doctor_name},\n\n"
        "Your account has been created in the Hospital Appointment "
        "Booking System.\n\n"
        "Use your registered email address to log in. "
        "Your password is not included in this email.\n"
    )

    if login_url:
        body += f"\nLogin page: {login_url}\n"

    body += "\nRegards,\nHospital Appointment Booking Team"
    return send_email(doctor_email, subject, body)


def appointment_email(
    to_email: str,
    subject: str,
    appointment,
    doctor_name: str,
) -> bool:
    """Send appointment information to one recipient."""
    body = (
        f"Appointment: {appointment.appointment_number}\n"
        f"Doctor: {doctor_name}\n"
        f"Date: {appointment.appointment_date}\n"
        f"Time: {appointment.slot_time}\n"
        f"Token: {appointment.token_number}\n"
        f"Status: {appointment.status}\n"
    )
    return send_email(to_email, subject, body)


def send_appointment_booking_emails(
    patient_email: str,
    doctor_email: str,
    appointment,
    doctor_name: str,
) -> bool:
    """Notify patient and doctor about a new booking."""
    patient_sent = appointment_email(
        patient_email,
        "Appointment Booking Confirmation",
        appointment,
        doctor_name,
    )

    doctor_sent = appointment_email(
        doctor_email,
        "New Patient Appointment",
        appointment,
        doctor_name,
    )

    return patient_sent and doctor_sent


